create table if not exists public.categorie (
  id_categorie bigint generated by default as identity primary key,
  nom_categorie text not null unique
);

create table if not exists public.produit (
  id_produit bigint generated by default as identity primary key,
  nom_produit text not null,
  description text not null,
  prix numeric(12, 2) not null check (prix >= 0),
  stock integer not null default 0 check (stock >= 0),
  image text,
  id_categorie bigint not null references public.categorie(id_categorie) on delete restrict
);

create table if not exists public.client (
  id_client bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  nom text,
  prenom text,
  email text,
  telephone text,
  cree_le timestamptz not null default timezone('utc', now())
);

create table if not exists public.commande (
  id_commande bigint generated by default as identity primary key,
  date_commande timestamptz not null default timezone('utc', now()),
  statut text not null default 'En attente',
  id_client bigint not null references public.client(id_client) on delete restrict
);

create table if not exists public.ligne_commande (
  id_ligne bigint generated by default as identity primary key,
  id_commande bigint not null references public.commande(id_commande) on delete cascade,
  id_produit bigint not null references public.produit(id_produit) on delete restrict,
  quantite integer not null check (quantite > 0),
  prix_unitaire numeric(12, 2) not null check (prix_unitaire >= 0),
  unique (id_commande, id_produit)
);

create table if not exists public.adresse_commande (
  id_adresse bigint generated by default as identity primary key,
  id_commande bigint not null unique references public.commande(id_commande) on delete cascade,
  adresse text not null,
  ville text not null,
  mode_livraison text not null,
  frais_livraison numeric(12, 2) not null default 0 check (frais_livraison >= 0)
);

create table if not exists public.paiement_commande (
  id_paiement bigint generated by default as identity primary key,
  id_commande bigint not null unique references public.commande(id_commande) on delete cascade,
  fournisseur text not null,
  statut text not null default 'Simule',
  montant numeric(12, 2) not null check (montant >= 0),
  cree_le timestamptz not null default timezone('utc', now())
);

create table if not exists public.panier_ligne (
  id_panier_ligne bigint generated by default as identity primary key,
  id_client bigint not null references public.client(id_client) on delete cascade,
  id_produit bigint not null references public.produit(id_produit) on delete cascade,
  quantite integer not null check (quantite > 0),
  unique (id_client, id_produit)
);

create table if not exists public.favori (
  id_favori bigint generated by default as identity primary key,
  id_client bigint not null references public.client(id_client) on delete cascade,
  id_produit bigint not null references public.produit(id_produit) on delete cascade,
  cree_le timestamptz not null default timezone('utc', now()),
  unique (id_client, id_produit)
);

create table if not exists public.profil_vendeur (
  id_profil bigint generated by default as identity primary key,
  id_client bigint not null unique references public.client(id_client) on delete cascade,
  plan text not null default 'starter' check (plan in ('starter', 'pro', 'entreprise')),
  date_debut date not null default current_date,
  date_fin date,
  actif boolean not null default true
);

create table if not exists public.produit_vendeur (
  id_produit bigint primary key references public.produit(id_produit) on delete cascade,
  id_client bigint not null references public.client(id_client) on delete cascade
);

create table if not exists public.demande_partenariat (
  id_partenariat bigint generated by default as identity primary key,
  id_client bigint not null references public.client(id_client) on delete cascade,
  type text not null,
  message text not null,
  statut text not null default 'En étude',
  cree_le timestamptz not null default timezone('utc', now())
);

create index if not exists idx_produit_categorie on public.produit(id_categorie);
create index if not exists idx_produit_nom on public.produit using gin (to_tsvector('simple', nom_produit));
create index if not exists idx_commande_client on public.commande(id_client);
create index if not exists idx_ligne_commande_commande on public.ligne_commande(id_commande);
create index if not exists idx_ligne_commande_produit on public.ligne_commande(id_produit);
create index if not exists idx_panier_client on public.panier_ligne(id_client);
create index if not exists idx_favori_client on public.favori(id_client);

