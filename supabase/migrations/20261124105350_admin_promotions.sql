begin;

create table public.promo_codes (
  id_promotion bigint generated by default as identity primary key,
  code text not null unique,
  type_remise text not null check (type_remise in ('pourcentage', 'montant_fixe')),
  valeur numeric(12, 2) not null,
  date_debut timestamptz not null default now(),
  date_fin timestamptz,
  limite_utilisation integer check (limite_utilisation is null or limite_utilisation > 0),
  actif boolean not null default true,
  cree_le timestamptz not null default now(),
  constraint promo_codes_discount check (
    valeur > 0 and (type_remise <> 'pourcentage' or valeur <= 100)
  ),
  constraint promo_codes_code_format check (code ~ '^[A-Z0-9_-]{3,30}$'),
  constraint promo_codes_date_range check (date_fin is null or date_fin > date_debut)
);

alter table public.promo_codes enable row level security;
revoke all on table public.promo_codes from public, anon, authenticated;

create table public.promo_code_uses (
  id_utilisation bigint generated by default as identity primary key,
  id_promotion bigint not null
    references public.promo_codes(id_promotion) on delete restrict,
  id_commande bigint not null unique
    references public.commande(id_commande) on delete restrict,
  id_client bigint not null
    references public.client(id_client) on delete restrict,
  montant_remise numeric(12, 2) not null check (montant_remise >= 0),
  utilise_le timestamptz not null default now()
);

create index promo_code_uses_promotion_idx
  on public.promo_code_uses(id_promotion);

alter table public.promo_code_uses enable row level security;
revoke all on table public.promo_code_uses from public, anon, authenticated;

insert into public.promo_codes (
  code,
  type_remise,
  valeur,
  date_debut,
  actif
)
values (
  'TOGO10',
  'pourcentage',
  10,
  now(),
  true
)
on conflict (code) do nothing;

create or replace function public.admin_upsert_promo(
  p_id_promotion bigint,
  p_code text,
  p_type_remise text,
  p_valeur numeric,
  p_date_debut timestamptz,
  p_date_fin timestamptz,
  p_limite_utilisation integer,
  p_actif boolean
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_promotion_id bigint;
  v_code text;
  v_existing public.promo_codes%rowtype;
begin
  if not public.is_admin() then
    raise exception 'Accès administrateur requis';
  end if;

  v_code := upper(trim(coalesce(p_code, '')));
  if v_code !~ '^[A-Z0-9_-]{3,30}$' then
    raise exception 'Le code doit contenir 3 à 30 caractères (A-Z, 0-9, tiret ou soulignement)';
  end if;
  if v_code = 'TOGO10' then
    raise exception 'TOGO10 est réservé à la compatibilité avec place_order et ne peut pas être modifié';
  end if;
  if p_type_remise is null or p_type_remise not in ('pourcentage', 'montant_fixe') then
    raise exception 'Type de remise invalide';
  end if;
  if p_valeur is null or p_valeur <= 0
     or (p_type_remise = 'pourcentage' and p_valeur > 100) then
    raise exception 'Valeur de remise invalide';
  end if;
  if p_date_debut is null or (p_date_fin is not null and p_date_fin <= p_date_debut) then
    raise exception 'Période de validité invalide';
  end if;
  if p_limite_utilisation is not null and p_limite_utilisation < 1 then
    raise exception 'La limite d’utilisation doit être supérieure à 0';
  end if;
  if p_actif is null then
    raise exception 'Le statut actif est obligatoire';
  end if;

  if p_id_promotion is null then
    insert into public.promo_codes (
      code,
      type_remise,
      valeur,
      date_debut,
      date_fin,
      limite_utilisation,
      actif
    )
    values (
      v_code,
      p_type_remise,
      p_valeur,
      p_date_debut,
      p_date_fin,
      p_limite_utilisation,
      p_actif
    )
    returning id_promotion into v_promotion_id;
  else
    select pc.*
    into v_existing
    from public.promo_codes pc
    where pc.id_promotion = p_id_promotion
    for update;

    if not found then
      raise exception 'Code promotionnel introuvable';
    end if;

    if exists (
      select 1
      from public.promo_code_uses pu
      where pu.id_promotion = p_id_promotion
    ) and (
      v_existing.code is distinct from v_code
      or v_existing.type_remise is distinct from p_type_remise
      or v_existing.valeur is distinct from p_valeur
      or date_trunc('milliseconds', v_existing.date_debut)
        is distinct from date_trunc('milliseconds', p_date_debut)
      or date_trunc('milliseconds', v_existing.date_fin)
        is distinct from date_trunc('milliseconds', p_date_fin)
    ) then
      raise exception 'Ce code a déjà été utilisé; son code, sa remise et sa période ne peuvent plus être modifiés.';
    end if;

    update public.promo_codes
    set code = v_code,
        type_remise = p_type_remise,
        valeur = p_valeur,
        date_debut = p_date_debut,
        date_fin = p_date_fin,
        limite_utilisation = p_limite_utilisation,
        actif = p_actif
    where id_promotion = p_id_promotion
    returning id_promotion into v_promotion_id;

  end if;

  return v_promotion_id;
end;
$$;

revoke all on function public.admin_upsert_promo(bigint, text, text, numeric, timestamptz, timestamptz, integer, boolean)
  from public, anon, authenticated;
grant execute on function public.admin_upsert_promo(bigint, text, text, numeric, timestamptz, timestamptz, integer, boolean)
  to authenticated;

create or replace function public.admin_delete_promo(p_id_promotion bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_code text;
begin
  if not public.is_admin() then
    raise exception 'Accès administrateur requis';
  end if;

  select pc.code
  into v_code
  from public.promo_codes pc
  where pc.id_promotion = p_id_promotion
  for update;

  if not found then
    raise exception 'Code promotionnel introuvable';
  end if;
  if v_code = 'TOGO10' then
    raise exception 'TOGO10 est réservé à la compatibilité avec place_order et ne peut pas être supprimé';
  end if;

  if exists (
    select 1
    from public.promo_code_uses pu
    where pu.id_promotion = p_id_promotion
  ) then
    raise exception 'Ce code a déjà été utilisé. Désactivez-le pour conserver son historique.';
  end if;

  delete from public.promo_codes pc
  where pc.id_promotion = p_id_promotion
    and not exists (
      select 1
      from public.promo_code_uses pu
      where pu.id_promotion = pc.id_promotion
    );

  if not found then
    raise exception 'Le code ne peut pas être supprimé';
  end if;

  return true;
end;
$$;

revoke all on function public.admin_delete_promo(bigint) from public, anon, authenticated;
grant execute on function public.admin_delete_promo(bigint) to authenticated;

create or replace function public.admin_list_promos()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_result jsonb;
begin
  if not public.is_admin() then
    raise exception 'Accès administrateur requis';
  end if;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'id_promotion', pc.id_promotion,
        'code', pc.code,
        'type_remise', pc.type_remise,
        'valeur', pc.valeur,
        'date_debut', pc.date_debut,
        'date_fin', pc.date_fin,
        'limite_utilisation', pc.limite_utilisation,
        'actif', pc.actif,
        'nombre_utilisations', coalesce(uses.nombre, 0),
        'cree_le', pc.cree_le
      )
      order by pc.cree_le desc, pc.id_promotion desc
    ),
    '[]'::jsonb
  )
  into v_result
  from public.promo_codes pc
  left join lateral (
    select count(*) as nombre
    from public.promo_code_uses pu
    where pu.id_promotion = pc.id_promotion
  ) uses on true;

  return v_result;
end;
$$;

revoke all on function public.admin_list_promos() from public, anon, authenticated;
grant execute on function public.admin_list_promos() to authenticated;

create or replace function public.preview_promo(p_code text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_client_id bigint;
  v_promotion public.promo_codes%rowtype;
  v_subtotal numeric(12, 2);
  v_cart_count integer;
  v_uses integer;
  v_discount numeric(12, 2);
  v_code text;
begin
  if auth.uid() is null then
    raise exception 'Authentification requise';
  end if;

  select cl.id_client
  into v_client_id
  from public.client cl
  where cl.user_id = auth.uid();

  if v_client_id is null then
    raise exception 'Profil client introuvable';
  end if;

  v_code := upper(trim(coalesce(p_code, '')));
  if v_code = '' then
    raise exception 'Saisissez un code promotionnel';
  end if;

  select pc.*
  into v_promotion
  from public.promo_codes pc
  where pc.code = v_code
    and pc.actif
    and pc.date_debut <= now()
    and (pc.date_fin is null or pc.date_fin >= now());

  if not found then
    raise exception 'Code promotionnel inconnu, inactif ou hors période de validité';
  end if;

  select count(*)
  into v_uses
  from public.promo_code_uses pu
  where pu.id_promotion = v_promotion.id_promotion;

  if v_promotion.limite_utilisation is not null
     and v_uses >= v_promotion.limite_utilisation then
    raise exception 'La limite d’utilisation de ce code est atteinte';
  end if;

  select coalesce(sum(pl.quantite * pr.prix), 0), count(*)
  into v_subtotal, v_cart_count
  from public.panier_ligne pl
  join public.produit pr on pr.id_produit = pl.id_produit
  where pl.id_client = v_client_id;

  if v_cart_count = 0 then
    raise exception 'Le panier est vide';
  end if;

  if v_promotion.type_remise = 'pourcentage' then
    v_discount := round(v_subtotal * v_promotion.valeur / 100, 2);
  else
    v_discount := least(v_subtotal, v_promotion.valeur);
  end if;

  return jsonb_build_object(
    'code', v_promotion.code,
    'type_remise', v_promotion.type_remise,
    'valeur', v_promotion.valeur,
    'sous_total', v_subtotal,
    'remise', v_discount
  );
end;
$$;

revoke all on function public.preview_promo(text) from public, anon, authenticated;
grant execute on function public.preview_promo(text) to authenticated;

create or replace function public.place_order_with_promo(
  p_adresse text,
  p_ville text,
  p_mode_livraison text,
  p_paiement text,
  p_code text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_client_id bigint;
  v_promotion public.promo_codes%rowtype;
  v_row record;
  v_order_id bigint;
  v_cart_count integer := 0;
  v_uses integer;
  v_subtotal numeric(12, 2) := 0;
  v_discount numeric(12, 2) := 0;
  v_shipping numeric(12, 2) := 0;
  v_total numeric(12, 2);
  v_code text;
begin
  if auth.uid() is null then
    raise exception 'Authentification requise';
  end if;

  select cl.id_client
  into v_client_id
  from public.client cl
  where cl.user_id = auth.uid();

  if v_client_id is null then
    raise exception 'Profil client introuvable';
  end if;

  v_code := upper(trim(coalesce(p_code, '')));

  if v_code = '' then
    v_order_id := public.place_order(
      p_adresse,
      p_ville,
      p_mode_livraison,
      p_paiement,
      null
    );

    select coalesce(sum(lc.quantite * lc.prix_unitaire), 0),
           ac.frais_livraison,
           pc.montant
    into v_subtotal, v_shipping, v_total
    from public.commande c
    join public.adresse_commande ac on ac.id_commande = c.id_commande
    join public.paiement_commande pc on pc.id_commande = c.id_commande
    left join public.ligne_commande lc on lc.id_commande = c.id_commande
    where c.id_commande = v_order_id
    group by ac.frais_livraison, pc.montant;

    return jsonb_build_object(
      'id_commande', v_order_id,
      'code', null,
      'sous_total', v_subtotal,
      'remise', 0,
      'frais_livraison', v_shipping,
      'total', v_total
    );
  end if;

  select pc.*
  into v_promotion
  from public.promo_codes pc
  where pc.code = v_code
  for update;

  if not found
     or not v_promotion.actif
     or v_promotion.date_debut > now()
     or (v_promotion.date_fin is not null and v_promotion.date_fin < now()) then
    raise exception 'Code promotionnel inconnu, inactif ou hors période de validité';
  end if;

  select count(*)
  into v_uses
  from public.promo_code_uses pu
  where pu.id_promotion = v_promotion.id_promotion;

  if v_promotion.limite_utilisation is not null
     and v_uses >= v_promotion.limite_utilisation then
    raise exception 'La limite d’utilisation de ce code est atteinte';
  end if;

  for v_row in
    select pl.quantite, pr.prix
    from public.panier_ligne pl
    join public.produit pr on pr.id_produit = pl.id_produit
    where pl.id_client = v_client_id
    for update of pl, pr
  loop
    v_subtotal := v_subtotal + v_row.quantite * v_row.prix;
    v_cart_count := v_cart_count + 1;
  end loop;

  if v_cart_count = 0 then
    raise exception 'Le panier est vide';
  end if;

  if v_promotion.type_remise = 'pourcentage' then
    v_discount := round(v_subtotal * v_promotion.valeur / 100, 2);
  else
    v_discount := least(v_subtotal, v_promotion.valeur);
  end if;

  v_order_id := public.place_order(
    p_adresse,
    p_ville,
    p_mode_livraison,
    p_paiement,
    null
  );

  if p_mode_livraison = 'express' then
    v_shipping := 3000;
  elsif p_mode_livraison = 'standard'
        and v_subtotal - v_discount < 100000 then
    v_shipping := 1500;
  end if;

  v_total := v_subtotal - v_discount + v_shipping;

  update public.adresse_commande
  set frais_livraison = v_shipping
  where id_commande = v_order_id;

  update public.paiement_commande
  set montant = v_total
  where id_commande = v_order_id;

  insert into public.promo_code_uses (
    id_promotion,
    id_commande,
    id_client,
    montant_remise
  )
  values (
    v_promotion.id_promotion,
    v_order_id,
    v_client_id,
    v_discount
  );

  return jsonb_build_object(
    'id_commande', v_order_id,
    'code', v_promotion.code,
    'sous_total', v_subtotal,
    'remise', v_discount,
    'frais_livraison', v_shipping,
    'total', v_total
  );
end;
$$;

revoke all on function public.place_order_with_promo(text, text, text, text, text)
  from public, anon, authenticated;
grant execute on function public.place_order_with_promo(text, text, text, text, text)
  to authenticated;

commit;
notify pgrst, 'reload schema';
